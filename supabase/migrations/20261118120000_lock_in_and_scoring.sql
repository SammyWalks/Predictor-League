create or replace function private.points_for(p_score text, p_home integer, p_away integer)
returns integer
language plpgsql
immutable
set search_path = public
as $$
declare
  home_goals integer;
  away_goals integer;
begin
  if p_score is null or p_home is null or p_away is null then
    return null;
  end if;
  if p_score !~ '^[0-9]{1,2}-[0-9]{1,2}$' then
    return null;
  end if;
  home_goals := split_part(p_score, '-', 1)::integer;
  away_goals := split_part(p_score, '-', 2)::integer;
  if home_goals > 20 or away_goals > 20 then
    return null;
  end if;
  if home_goals = p_home and away_goals = p_away then
    return 3;
  end if;
  if sign(home_goals - away_goals) = sign(p_home - p_away) then
    return 1;
  end if;
  return 0;
end;
$$;

create or replace function private.canonical_score(p_score text)
returns text
language plpgsql
immutable
set search_path = public
as $$
declare
  home_goals integer;
  away_goals integer;
begin
  if p_score is null or btrim(p_score) !~ '^[0-9]{1,2}-[0-9]{1,2}$' then
    return null;
  end if;
  home_goals := split_part(btrim(p_score), '-', 1)::integer;
  away_goals := split_part(btrim(p_score), '-', 2)::integer;
  if home_goals > 20 or away_goals > 20 then
    return null;
  end if;
  return home_goals::text || '-' || away_goals::text;
end;
$$;

create or replace function private.require_user(p_token text)
returns public.users
language plpgsql
security definer
set search_path = public, private
as $$
declare
  actor public.users%rowtype;
begin
  if p_token is null or length(p_token) < 16 then
    raise exception 'Not logged in';
  end if;
  select users.* into actor
  from private.sessions s
  join public.users users on users.id = s.user_id
  where s.token = p_token
    and s.expires_at > now();
  if actor.id is null then
    raise exception 'Session expired. Log in again.';
  end if;
  return actor;
end;
$$;

