create or replace function public.scheduled_apply_scores(p_secret text, p_scores jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, private
as $$
declare
  item jsonb;
  applied integer := 0;
  fixture_id integer;
  home_goals integer;
  away_goals integer;
begin
  perform private.require_secret(p_secret);
  if p_scores is null or jsonb_typeof(p_scores) <> 'array' then
    raise exception 'Scores must be a list';
  end if;
  for item in select value from jsonb_array_elements(p_scores)
  loop
    fixture_id := (item->>'fixtureId')::integer;
    home_goals := (item->>'home')::integer;
    away_goals := (item->>'away')::integer;
    if home_goals is null or away_goals is null or home_goals < 0 or away_goals < 0 or home_goals > 20 or away_goals > 20 then
      continue;
    end if;
    update public.fixtures
    set actual_home = home_goals, actual_away = away_goals
    where id = fixture_id
      and actual_home is null
      and actual_away is null;
    if found then
      applied := applied + 1;
    end if;
  end loop;
  return jsonb_build_object('ok', true, 'applied', applied);
end;
$$;

