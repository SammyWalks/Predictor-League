-- 1. Open the Supabase project used by the live site (pilytmsoimdguzfchubv).
-- 2. SQL Editor → New query → paste this whole file → Run.
-- 3. Then run 20261118120100_remove_kieran_savage.sql if Kieran Savage should leave the game.
-- 4. Set a scoring secret (see the bottom of this file) and the Netlify env vars in the pull request notes.
--
-- This file is safe to run more than once. It does not delete players, predictions,
-- or season points. Existing user rows are left as they are (the seed uses
-- ON CONFLICT DO NOTHING). Sam Walker is marked as the admin so someone can
-- enter final scores. Change that afterwards if you want a different admin.
--
-- What you get:
-- * Draft predictions stay private. Other players cannot read them.
-- * Locking copies those picks into published_picks, which everyone can read.
-- * After lock-in, that player cannot edit the week.
-- * Final scores are typed by an admin, or filled in on Tuesday when still blank.
-- * Calculating points is safe to repeat: it stores the points on each locked
--   pick and only changes a player's season total by the difference.
-- * Scoring is the rule already used on the old results page:
--     3 points for an exact score, 1 point for the correct result, 0 otherwise.

