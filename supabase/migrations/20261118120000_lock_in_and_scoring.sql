create or replace function public.admin_save_result(
  p_token text,
  p_fixture_id integer,
  p_home integer,
  p_away integer
)
returns jsonb
language plpgsql
security definer
set search_path = public, private
as $$
begin
  perform private.require_admin(p_token);
  if p_home is null or p_away is null then
    update public.fixtures
    set actual_home = null, actual_away = null
    where id = p_fixture_id;
  else
    if p_home < 0 or p_away < 0 or p_home > 20 or p_away > 20 then
      raise exception 'Scores must be whole numbers from 0 to 20';
    end if;
    update public.fixtures
    set actual_home = p_home, actual_away = p_away
    where id = p_fixture_id;
  end if;
  if not found then
    raise exception 'Fixture not found';
  end if;
  return jsonb_build_object('ok', true);
end;
$$;

